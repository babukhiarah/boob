/* ============================================================
   pdf.js
   توليد PDF متعدد الصفحات + إرسال بالإيميل عبر EmailJS
   ============================================================ */

const PDFGen = {
  /** يبني PDF من وردية، يرجّع jsPDF instance */
  build(shift, managerName, approvedAt) {
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF({ unit: "pt", format: "a4" });
    const W = doc.internal.pageSize.getWidth();
    const sum = Calc.summary(shift);

    // ---- helpers ----
    const line = (y) => { doc.setDrawColor(180); doc.line(40, y, W - 40, y); };
    const header = (title) => {
      doc.setFillColor(31, 122, 58);
      doc.rect(0, 0, W, 50, "F");
      doc.setTextColor(255);
      doc.setFontSize(16);
      doc.text(`${shift.branch} - ${title}`, W / 2, 32, { align: "center" });
      doc.setTextColor(0);
    };
    const row = (y, label, value) => {
      doc.setFontSize(11);
      doc.text(String(label), W - 50, y, { align: "right" });
      doc.text(String(value), 50, y, { align: "left" });
    };

    // ===== Page 1: Summary =====
    header("Shift Summary");
    let y = 80;
    row(y, "Employee", shift.employee); y += 18;
    row(y, "Shift", Utils.shiftLabel(shift.shiftKey)); y += 18;
    row(y, "Date", Utils.dateOnly(shift.createdAt)); y += 18;
    row(y, "Started", Utils.timeOnly(shift.createdAt)); y += 18;
    row(y, "Submitted", shift.submittedAt ? Utils.timeOnly(shift.submittedAt) : "-"); y += 24;
    line(y); y += 14;

    row(y, "Cash Start", Utils.fmt(shift.cash.start)); y += 16;
    row(y, "Cash Delivered", Utils.fmt(shift.cash.delivered)); y += 16;
    row(y, "Sales", Utils.fmt(sum.sales)); y += 16;
    row(y, "Visa Diff", Utils.fmt(sum.visaDiff)); y += 16;
    row(y, "Click Diff", Utils.fmt(sum.clickDiff)); y += 16;
    row(y, "Incoming", Utils.fmt(shift.incoming)); y += 16;
    row(y, "Debts", Utils.fmt(shift.debts)); y += 16;
    row(y, "Expenses", Utils.fmt(sum.expenses)); y += 16;
    row(y, "Payments", Utils.fmt(sum.payments)); y += 20;
    line(y); y += 14;
    doc.setFontSize(13); doc.setFont(undefined, "bold");
    row(y, "Expected Cash", Utils.fmt(sum.expected)); y += 18;
    row(y, "Difference",   Utils.fmt(sum.diff));
    doc.setFont(undefined, "normal");

    // ===== Page 2: Inventory details =====
    doc.addPage();
    header("Inventory Details");
    y = 70;
    doc.setFontSize(10);
    doc.text("Product", 50, y);
    doc.text("Price", 200, y);
    doc.text("Recv", 250, y);
    doc.text("Add",  300, y);
    doc.text("Deliv",350, y);
    doc.text("Sold", 400, y);
    doc.text("Value",460, y);
    y += 8; line(y); y += 12;

    shift.products.forEach(p => {
      const c = Calc.productLine(p);
      if (y > 780) { doc.addPage(); header("Inventory Details (cont.)"); y = 70; }
      doc.text(String(p.name).slice(0, 24), 50, y);
      doc.text(Utils.fmt(p.price), 200, y);
      doc.text(String(p.received), 250, y);
      doc.text(String(p.added), 300, y);
      doc.text(String(p.delivered === "" ? "-" : p.delivered), 350, y);
      doc.text(String(c.sold), 400, y);
      doc.text(Utils.fmt(c.value), 460, y);
      y += 14;
    });

    // ===== Page 3: Inventory image =====
    doc.addPage();
    header("Inventory Image");
    if (shift.inventoryImage) {
      try {
        const type = shift.inventoryImage.startsWith("data:image/png") ? "PNG" : "JPEG";
        doc.addImage(shift.inventoryImage, type, 60, 80, W - 120, 600, undefined, "FAST");
      } catch (e) {
        doc.text("Failed to embed image", 50, 100);
      }
    } else {
      doc.text("No inventory image", 50, 100);
    }

    // ===== Page 4: Manager approval =====
    doc.addPage();
    header("Manager Approval");
    y = 100;
    row(y, "Approved By", managerName || "-"); y += 20;
    row(y, "Approved At", approvedAt ? new Date(approvedAt).toLocaleString("en-GB", { hour12: false }) : "-"); y += 20;
    row(y, "Shift ID", shift.id); y += 20;
    doc.setFontSize(10); doc.setTextColor(120);
    doc.text("Generated by Shift Management System", W / 2, 800, { align: "center" });

    return doc;
  },

  /** يحفظ PDF محلياً */
  save(shift, managerName, approvedAt) {
    const doc = this.build(shift, managerName, approvedAt);
    const fname = `shift_${shift.shiftKey}_${shift.employee}_${shift.id}.pdf`.replace(/\s+/g, "_");
    doc.save(fname);
    DB.pushAudit({ action: "تصدير PDF", user: managerName, details: shift.id });
  },

  /** إرسال PDF عبر EmailJS - مجاناً */
  async emailToManager(shift, managerName, approvedAt) {
    const settings = DB.getSettings();
    const { publicKey, serviceId, templateId } = settings.emailjs || {};
    if (!settings.managerEmail || !publicKey || !serviceId || !templateId) {
      Utils.toast("إعدادات الإيميل غير مكتملة (EmailJS)", "warning");
      return false;
    }
    if (!window.emailjs) { Utils.toast("EmailJS لم يُحمّل", "danger"); return false; }

    try {
      const doc = this.build(shift, managerName, approvedAt);
      const base64 = doc.output("datauristring").split(",")[1];

      emailjs.init(publicKey);
      await emailjs.send(serviceId, templateId, {
        to_email: settings.managerEmail,
        branch: shift.branch,
        employee: shift.employee,
        shift: Utils.shiftLabel(shift.shiftKey),
        date: Utils.dateOnly(shift.createdAt),
        difference: Utils.fmt(Calc.difference(shift)),
        pdf_base64: base64,
      });
      Utils.toast("تم إرسال PDF للإيميل");
      return true;
    } catch (e) {
      console.error(e);
      Utils.toast("فشل إرسال الإيميل: " + (e?.text || e?.message || ""), "danger");
      return false;
    }
  },
};